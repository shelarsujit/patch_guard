"""Drive the patch-guard MCP server over stdio and record what it says.

Evidence, not decoration. The README claims any MCP-capable agent can call the
same three gates the supervisor uses; this exercises that claim through a real
stdio client -- a subprocess, a protocol handshake, and three tool calls -- and
writes the transcript to docs/mcp_demo.md.

The scenario is the one that matters: a patch that makes the reported test pass
while breaking tests in a module the agent was never asked to touch. Gate 1 says
"fixed". Gate 2 says "you broke four other things". An agent trusting only the
first would submit it.

    python eval/mcp_demo.py
"""

from __future__ import annotations

import asyncio
import json
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from mcp import ClientSession, StdioServerParameters  # noqa: E402
from mcp.client.stdio import stdio_client  # noqa: E402

from eval import harness  # noqa: E402
from patch_guard import config, workspace  # noqa: E402

_FIX_LINES = [
    '_PUNCTUATION = ".,:;!?()[]{}"',
    "",
    "",
    "def normalize(text):",
    '    """Collapse whitespace, lowercase, strip punctuation."""',
    "    cleaned = text.lower()",
    "    for mark in _PUNCTUATION:",
    '        cleaned = cleaned.replace(mark, "")',
    '    return " ".join(cleaned.split())',
    "",
]
TEMPTING_FIX = chr(10).join(_FIX_LINES)

async def main() -> None:
    case = harness.load_cases(["coupled__slugify"])[0]
    ws = workspace.build(case, Path(tempfile.mkdtemp()) / "repo")
    # The patch under review: fixes the reported bug via the shared helper.
    ws.write("python_programs/textlib.py", TEMPTING_FIX)

    params = StdioServerParameters(
        command=sys.executable,
        args=[str(config.REPO_ROOT / "patch_guard" / "mcp_server.py")],
    )

    lines: list[str] = []

    def say(text: str = "") -> None:
        print(text)
        lines.append(text)

    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()

            tools = await session.list_tools()
            say("## Tools advertised by the server")
            say()
            for t in tools.tools:
                say(f"- `{t.name}` — {(t.description or '').strip().splitlines()[0]}")
            say()

            calls = [
                ("run_target_test",
                 {"workdir": str(ws.root), "test_path": case["target_test"],
                  "expected_node_ids": case["fail_to_pass"]}),
                ("run_regression_suite",
                 {"workdir": str(ws.root),
                  "previously_passing_node_ids": case["pass_to_pass"]}),
                ("assert_tests_unmodified",
                 {"workdir": str(ws.root), "pristine_dir": str(ws.pristine_root),
                  "protected_paths": case["protected_paths"]}),
            ]

            say("## The three gates, called over MCP")
            say()
            for name, args in calls:
                result = await session.call_tool(name, args)
                payload = "".join(c.text for c in result.content if hasattr(c, "text"))
                try:
                    payload = json.dumps(json.loads(payload), indent=2)[:900]
                except json.JSONDecodeError:
                    payload = payload[:900]
                shown = {k: v for k, v in args.items() if k != "expected_node_ids"}
                say(f"### `{name}`")
                say()
                say(f"```json\n{json.dumps(shown, indent=2)}\n```")
                say()
                say(f"```json\n{payload}\n```")
                say()

    header = [
        "# MCP server transcript",
        "",
        f"Generated by `eval/mcp_demo.py` on "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%d')}. Not hand-written.",
        "",
        "A real stdio client: the server runs as a subprocess, the session does a",
        "protocol handshake, and the three gates are invoked as MCP tools. They are",
        "the same functions the LangGraph supervisor calls -- there is no second",
        "implementation.",
        "",
        "**The patch under review** fixes the reported `slugify` bug by changing the",
        "shared `textlib.normalize`. The target test passes. Four tests belonging to",
        "modules the agent was never asked to touch do not.",
        "",
    ]
    out = config.REPO_ROOT / "docs" / "mcp_demo.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    asyncio.run(main())
